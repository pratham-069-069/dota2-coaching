import React, { useState, useEffect } from "react";
import { predictDraft, recommendPicks, recommendItems } from "../services/api";
import { Plus, X, Sparkles, TrendingUp, ShieldCheck, Zap, RefreshCw, Ban, ShieldAlert, Clock, RotateCcw, Copy, Check } from "lucide-react";
import DraftPowerCurve from "./DraftPowerCurve";

export default function DraftRoom({ heroes }) {
  const [radiantPicks, setRadiantPicks] = useState([1, 5]); // Anti-Mage, Crystal Maiden
  const [direPicks, setDirePicks] = useState([8, 14]); // Juggernaut, Pudge
  const [bans, setBans] = useState([74]); // Invoker
  const [targetTeam, setTargetTeam] = useState("radiant");
  const [winRates, setWinRates] = useState({ radiant: 51.9, dire: 48.1 });
  const [recommendations, setRecommendations] = useState([]);
  const [itemAdvice, setItemAdvice] = useState(null);
  const [loadingRecs, setLoadingRecs] = useState(false);
  const [searchQuery, setSearchQuery] = useState("");
  const [copiedDraft, setCopiedDraft] = useState(false);

  const heroMap = React.useMemo(() => {
    const map = {};
    heroes.forEach((h) => {
      map[h.hero_id] = h;
    });
    return map;
  }, [heroes]);

  const resetDraft = () => {
    setRadiantPicks([]);
    setDirePicks([]);
    setBans([]);
    setRecommendations([]);
    setItemAdvice(null);
  };

  const copyDraftBriefing = () => {
    const radNames = radiantPicks.map((id) => heroMap[id]?.name || `Hero ${id}`).join(", ") || "None";
    const direNames = direPicks.map((id) => heroMap[id]?.name || `Hero ${id}`).join(", ") || "None";
    const banNames = bans.map((id) => heroMap[id]?.name || `Hero ${id}`).join(", ") || "None";
    const adv = winRates.radiant > winRates.dire
      ? `Radiant +${(winRates.radiant - 50).toFixed(1)}% Advantage`
      : `Dire +${(winRates.dire - 50).toFixed(1)}% Advantage`;

    const lines = [
      "========================================",
      "🛡️ AEGIS DOTA 2 COMPETITIVE DRAFT BRIEFING",
      "========================================",
      `RADIANT (${winRates.radiant}%): ${radNames}`,
      `DIRE (${winRates.dire}%): ${direNames}`,
      `BANS: ${banNames}`,
      `WIN RATE SPREAD: ${adv}`,
      "",
    ];

    if (recommendations && recommendations.length > 0) {
      lines.push(`TOP AI NEXT-PICK RECOMMENDATIONS (${targetTeam.toUpperCase()}):`);
      recommendations.slice(0, 3).forEach((r, i) => {
        lines.push(`  ${i + 1}. ${r.hero_name} - Projected WR: ${(r.projected_win_prob * 100).toFixed(1)}% (${r.reasons.join(", ")})`);
      });
      lines.push("");
    }

    if (itemAdvice && itemAdvice.situational_counters && itemAdvice.situational_counters.length > 0) {
      lines.push(`TACTICAL COUNTER-ITEMS FOR ${itemAdvice.hero_name.toUpperCase()}:`);
      itemAdvice.situational_counters.forEach((item) => {
        lines.push(`  • ${item.item_name} (~${item.target_timing_minutes}m target) vs ${item.countering_heroes.join(", ")}: "${item.strategic_rationale}"`);
      });
    }

    lines.push("========================================");
    lines.push("Generated by Aegis Coaching Intelligence Platform");

    navigator.clipboard.writeText(lines.join("\n"));
    setCopiedDraft(true);
    setTimeout(() => setCopiedDraft(false), 2500);
  };

  // Update Win Probability when picks change
  useEffect(() => {
    async function updatePredictions() {
      const res = await predictDraft(radiantPicks, direPicks);
      if (res && res.radiant_win_prob !== undefined) {
        setWinRates({
          radiant: Number((res.radiant_win_prob * 100).toFixed(1)),
          dire: Number((res.dire_win_prob * 100).toFixed(1)),
        });
      }
    }
    updatePredictions();
  }, [radiantPicks, direPicks]);

  // Update AI Recommendations and Situational Items
  const fetchRecsAndItems = async () => {
    setLoadingRecs(true);
    const ally = targetTeam === "radiant" ? radiantPicks : direPicks;
    const enemy = targetTeam === "radiant" ? direPicks : radiantPicks;

    const recs = await recommendPicks({
      allyPicks: ally,
      enemyPicks: enemy,
      bans,
      targetTeam,
      topN: 5,
    });
    setRecommendations(recs);

    // If ally has picks, fetch situational items against enemy draft
    if (ally.length > 0 && enemy.length > 0) {
      const items = await recommendItems(ally[0], enemy);
      if (items) setItemAdvice(items);
    } else {
      setItemAdvice(null);
    }

    setLoadingRecs(false);
  };

  useEffect(() => {
    fetchRecsAndItems();
  }, [radiantPicks, direPicks, bans, targetTeam]);

  const addHero = (heroId, team) => {
    if (radiantPicks.includes(heroId) || direPicks.includes(heroId) || bans.includes(heroId)) return;
    if (team === "radiant" && radiantPicks.length < 5) {
      setRadiantPicks([...radiantPicks, heroId]);
    } else if (team === "dire" && direPicks.length < 5) {
      setDirePicks([...direPicks, heroId]);
    }
  };

  const removeHero = (heroId, team) => {
    if (team === "radiant") {
      setRadiantPicks(radiantPicks.filter((id) => id !== heroId));
    } else {
      setDirePicks(direPicks.filter((id) => id !== heroId));
    }
  };

  const addBan = (heroId) => {
    if (radiantPicks.includes(heroId) || direPicks.includes(heroId) || bans.includes(heroId)) return;
    if (bans.length < 10) {
      setBans([...bans, heroId]);
    }
  };

  const removeBan = (heroId) => {
    setBans(bans.filter((id) => id !== heroId));
  };

  const filteredHeroes = heroes.filter((h) => {
    const isPickedOrBanned = radiantPicks.includes(h.hero_id) || direPicks.includes(h.hero_id) || bans.includes(h.hero_id);
    const matchesSearch = h.name.toLowerCase().includes(searchQuery.toLowerCase());
    return !isPickedOrBanned && matchesSearch;
  });

  return (
    <div style={{ padding: "1.5rem 0", maxWidth: "1400px", margin: "0 auto" }}>
      {/* Top Drafting Arena */}
      <div style={{
        display: "grid",
        gridTemplateColumns: "1fr 340px 1fr",
        gap: "1.5rem",
        marginBottom: "1.5rem",
        alignItems: "stretch",
      }}>
        {/* RADIANT TEAM (Left) */}
        <div className="glass-panel" style={{
          padding: "1.5rem",
          borderTop: "3px solid var(--radiant-green)",
          boxShadow: "0 10px 30px rgba(0, 245, 155, 0.08)",
        }}>
          <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "1rem" }}>
            <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
              <span style={{ width: "10px", height: "10px", borderRadius: "50%", background: "var(--radiant-green)", display: "inline-block", boxShadow: "0 0 10px var(--radiant-green)" }} />
              <h3 className="title-dota" style={{ color: "var(--radiant-green)", fontSize: "1.1rem" }}>Radiant Squad</h3>
            </div>
            <span className="badge badge-radiant">{radiantPicks.length} / 5 Picked</span>
          </div>

          <div style={{ display: "flex", flexDirection: "column", gap: "10px" }}>
            {[0, 1, 2, 3, 4].map((slotIndex) => {
              const hid = radiantPicks[slotIndex];
              const hero = hid ? heroMap[hid] : null;
              return (
                <div key={slotIndex} style={{
                  height: "54px",
                  borderRadius: "var(--radius-sm)",
                  background: hero ? "rgba(0, 245, 155, 0.06)" : "rgba(255, 255, 255, 0.02)",
                  border: `1px solid ${hero ? "rgba(0, 245, 155, 0.25)" : "rgba(255, 255, 255, 0.05)"}`,
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "space-between",
                  padding: "0 14px",
                  transition: "all 0.2s ease",
                }}>
                  {hero ? (
                    <>
                      <div style={{ display: "flex", alignItems: "center", gap: "12px" }}>
                        <span style={{ fontFamily: "var(--font-mono)", fontSize: "0.8rem", color: "var(--radiant-green)", fontWeight: 700 }}>
                          #{slotIndex + 1}
                        </span>
                        <div>
                          <div style={{ fontWeight: 600, color: "#fff", fontSize: "0.95rem" }}>{hero.name}</div>
                          <div style={{ fontSize: "0.72rem", color: "var(--text-muted)" }}>
                            Win Rate: {(hero.win_rate * 100).toFixed(1)}%
                          </div>
                        </div>
                      </div>
                      <button
                        onClick={() => removeHero(hero.hero_id, "radiant")}
                        style={{
                          background: "none",
                          border: "none",
                          color: "var(--text-faint)",
                          cursor: "pointer",
                          display: "flex",
                          alignItems: "center",
                        }}
                      >
                        <X size={16} />
                      </button>
                    </>
                  ) : (
                    <span style={{ color: "var(--text-faint)", fontSize: "0.85rem", fontStyle: "italic" }}>
                      Empty Pick Slot #{slotIndex + 1}
                    </span>
                  )}
                </div>
              );
            })}
          </div>
        </div>

        {/* CENTER LIVE WIN PROBABILITY GAUGE */}
        <div className="glass-panel" style={{
          padding: "1.5rem",
          display: "flex",
          flexDirection: "column",
          justifyContent: "center",
          alignItems: "center",
          textAlign: "center",
          position: "relative",
          overflow: "hidden",
        }}>
          <div style={{
            position: "absolute",
            top: 0,
            left: 0,
            right: 0,
            height: "3px",
            background: "linear-gradient(90deg, var(--radiant-green) 0%, var(--dire-crimson) 100%)",
          }} />

          <div style={{ fontSize: "0.75rem", fontFamily: "var(--font-mono)", color: "var(--text-muted)", letterSpacing: "0.08em", marginBottom: "4px" }}>
            XGBOOST DRAFT ENGINE
          </div>
          <div className="title-dota" style={{ fontSize: "1.2rem", fontWeight: 700, color: "var(--aegis-gold)", marginBottom: "1rem" }}>
            Live Win Probability
          </div>

          <div style={{ display: "flex", justifyContent: "space-between", width: "100%", marginBottom: "8px" }}>
            <div>
              <div className="font-stats" style={{ fontSize: "2rem", color: "var(--radiant-green)" }}>
                {winRates.radiant}%
              </div>
              <div style={{ fontSize: "0.75rem", color: "var(--radiant-green)", fontWeight: 600 }}>RADIANT</div>
            </div>
            <div style={{ display: "flex", alignItems: "center", color: "var(--text-faint)", fontWeight: 700 }}>
              VS
            </div>
            <div>
              <div className="font-stats" style={{ fontSize: "2rem", color: "var(--dire-crimson)" }}>
                {winRates.dire}%
              </div>
              <div style={{ fontSize: "0.75rem", color: "var(--dire-crimson)", fontWeight: 600 }}>DIRE</div>
            </div>
          </div>

          {/* Dual Tug-of-War Bar */}
          <div style={{
            width: "100%",
            height: "12px",
            borderRadius: "6px",
            background: "#1a2232",
            overflow: "hidden",
            display: "flex",
            margin: "0.75rem 0 1.25rem 0",
            border: "1px solid rgba(255, 255, 255, 0.08)",
          }}>
            <div style={{
              width: `${winRates.radiant}%`,
              background: "linear-gradient(90deg, #00f59b 0%, #00d084 100%)",
              transition: "width 0.4s cubic-bezier(0.16, 1, 0.3, 1)",
              boxShadow: "0 0 10px rgba(0, 245, 155, 0.5)",
            }} />
            <div style={{
              width: `${winRates.dire}%`,
              background: "linear-gradient(90deg, #ff4d5a 0%, #ff3344 100%)",
              transition: "width 0.4s cubic-bezier(0.16, 1, 0.3, 1)",
              boxShadow: "0 0 10px rgba(255, 51, 68, 0.5)",
            }} />
          </div>

          <div style={{
            fontSize: "0.75rem",
            color: "var(--text-muted)",
            background: "rgba(255, 255, 255, 0.03)",
            padding: "6px 12px",
            borderRadius: "4px",
            fontFamily: "var(--font-mono)",
          }}>
            {winRates.radiant > winRates.dire
              ? `Radiant +${(winRates.radiant - 50).toFixed(1)}% Advantage`
              : `Dire +${(winRates.dire - 50).toFixed(1)}% Advantage`}
          </div>

          {/* Target team selector for pick recommendation */}
          <div style={{ marginTop: "1.2rem", width: "100%" }}>
            <div style={{ fontSize: "0.75rem", color: "var(--text-faint)", marginBottom: "6px", textTransform: "uppercase" }}>
              Recommend Next Pick For:
            </div>
            <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: "6px" }}>
              <button
                onClick={() => setTargetTeam("radiant")}
                style={{
                  padding: "6px 10px",
                  borderRadius: "4px",
                  fontSize: "0.8rem",
                  fontWeight: 700,
                  cursor: "pointer",
                  background: targetTeam === "radiant" ? "var(--radiant-green)" : "rgba(255, 255, 255, 0.04)",
                  color: targetTeam === "radiant" ? "#000" : "var(--text-muted)",
                  border: "none",
                  transition: "all 0.2s ease",
                }}
              >
                Radiant
              </button>
              <button
                onClick={() => setTargetTeam("dire")}
                style={{
                  padding: "6px 10px",
                  borderRadius: "4px",
                  fontSize: "0.8rem",
                  fontWeight: 700,
                  cursor: "pointer",
                  background: targetTeam === "dire" ? "var(--dire-crimson)" : "rgba(255, 255, 255, 0.04)",
                  color: targetTeam === "dire" ? "#fff" : "var(--text-muted)",
                  border: "none",
                  transition: "all 0.2s ease",
                }}
              >
                Dire
              </button>
            </div>

            {/* Action Buttons: Reset Draft & Copy Briefing */}
            <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: "6px", marginTop: "10px" }}>
              <button
                onClick={resetDraft}
                style={{
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "center",
                  gap: "5px",
                  padding: "6px 8px",
                  borderRadius: "4px",
                  background: "rgba(255, 255, 255, 0.04)",
                  border: "1px solid var(--border-subtle)",
                  color: "var(--text-muted)",
                  fontSize: "0.75rem",
                  fontWeight: 600,
                  cursor: "pointer",
                }}
                title="Reset all picks and bans"
              >
                <RotateCcw size={13} /> Reset Draft
              </button>
              <button
                onClick={copyDraftBriefing}
                style={{
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "center",
                  gap: "5px",
                  padding: "6px 8px",
                  borderRadius: "4px",
                  background: copiedDraft ? "rgba(0, 245, 155, 0.15)" : "rgba(245, 166, 35, 0.12)",
                  border: `1px solid ${copiedDraft ? "var(--radiant-green)" : "rgba(245, 166, 35, 0.35)"}`,
                  color: copiedDraft ? "var(--radiant-green)" : "var(--aegis-gold)",
                  fontSize: "0.75rem",
                  fontWeight: 600,
                  cursor: "pointer",
                }}
                title="Copy formatted draft briefing for Discord/Team chat"
              >
                {copiedDraft ? <Check size={13} /> : <Copy size={13} />}
                {copiedDraft ? "Copied!" : "Copy Briefing"}
              </button>
            </div>

            {/* Visual Draft Power Spike Scaling Curve */}
            <DraftPowerCurve radiantPicks={radiantPicks} direPicks={direPicks} heroMap={heroMap} />
          </div>
        </div>

        {/* DIRE TEAM (Right) */}
        <div className="glass-panel" style={{
          padding: "1.5rem",
          borderTop: "3px solid var(--dire-crimson)",
          boxShadow: "0 10px 30px rgba(255, 51, 68, 0.08)",
        }}>
          <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "1rem" }}>
            <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
              <span style={{ width: "10px", height: "10px", borderRadius: "50%", background: "var(--dire-crimson)", display: "inline-block", boxShadow: "0 0 10px var(--dire-crimson)" }} />
              <h3 className="title-dota" style={{ color: "var(--dire-crimson)", fontSize: "1.1rem" }}>Dire Squad</h3>
            </div>
            <span className="badge badge-dire">{direPicks.length} / 5 Picked</span>
          </div>

          <div style={{ display: "flex", flexDirection: "column", gap: "10px" }}>
            {[0, 1, 2, 3, 4].map((slotIndex) => {
              const hid = direPicks[slotIndex];
              const hero = hid ? heroMap[hid] : null;
              return (
                <div key={slotIndex} style={{
                  height: "54px",
                  borderRadius: "var(--radius-sm)",
                  background: hero ? "rgba(255, 51, 68, 0.06)" : "rgba(255, 255, 255, 0.02)",
                  border: `1px solid ${hero ? "rgba(255, 51, 68, 0.25)" : "rgba(255, 255, 255, 0.05)"}`,
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "space-between",
                  padding: "0 14px",
                  transition: "all 0.2s ease",
                }}>
                  {hero ? (
                    <>
                      <div style={{ display: "flex", alignItems: "center", gap: "12px" }}>
                        <span style={{ fontFamily: "var(--font-mono)", fontSize: "0.8rem", color: "var(--dire-crimson)", fontWeight: 700 }}>
                          #{slotIndex + 1}
                        </span>
                        <div>
                          <div style={{ fontWeight: 600, color: "#fff", fontSize: "0.95rem" }}>{hero.name}</div>
                          <div style={{ fontSize: "0.72rem", color: "var(--text-muted)" }}>
                            Win Rate: {(hero.win_rate * 100).toFixed(1)}%
                          </div>
                        </div>
                      </div>
                      <button
                        onClick={() => removeHero(hero.hero_id, "dire")}
                        style={{
                          background: "none",
                          border: "none",
                          color: "var(--text-faint)",
                          cursor: "pointer",
                          display: "flex",
                          alignItems: "center",
                        }}
                      >
                        <X size={16} />
                      </button>
                    </>
                  ) : (
                    <span style={{ color: "var(--text-faint)", fontSize: "0.85rem", fontStyle: "italic" }}>
                      Empty Pick Slot #{slotIndex + 1}
                    </span>
                  )}
                </div>
              );
            })}
          </div>
        </div>
      </div>

      {/* BAN PHASE BAR */}
      <div className="glass-panel" style={{
        padding: "0.8rem 1.2rem",
        marginBottom: "1.5rem",
        display: "flex",
        alignItems: "center",
        justifyContent: "space-between",
        borderLeft: "4px solid #ef4444",
      }}>
        <div style={{ display: "flex", alignItems: "center", gap: "10px" }}>
          <Ban size={18} color="#ef4444" />
          <span style={{ fontSize: "0.85rem", fontWeight: 700, color: "#f87171", textTransform: "uppercase" }}>
            Draft Ban Phase ({bans.length} Banned):
          </span>
          <div style={{ display: "flex", flexWrap: "wrap", gap: "6px" }}>
            {bans.map((bid) => {
              const h = heroMap[bid];
              return (
                <span key={bid} style={{
                  display: "inline-flex",
                  alignItems: "center",
                  gap: "6px",
                  padding: "3px 8px",
                  borderRadius: "4px",
                  background: "rgba(239, 68, 68, 0.15)",
                  border: "1px solid rgba(239, 68, 68, 0.4)",
                  color: "#fca5a5",
                  fontSize: "0.8rem",
                  fontFamily: "var(--font-mono)",
                }}>
                  {h ? h.name : `Hero ${bid}`}
                  <X size={13} style={{ cursor: "pointer" }} onClick={() => removeBan(bid)} />
                </span>
              );
            })}
            {bans.length === 0 && (
              <span style={{ fontSize: "0.8rem", color: "var(--text-faint)", fontStyle: "italic" }}>
                No heroes currently banned. Click "+ BAN" in the roster to ban.
              </span>
            )}
          </div>
        </div>

        {bans.length > 0 && (
          <button
            onClick={() => setBans([])}
            style={{
              background: "rgba(239, 68, 68, 0.12)",
              border: "1px solid rgba(239, 68, 68, 0.3)",
              color: "#fca5a5",
              borderRadius: "4px",
              padding: "4px 10px",
              fontSize: "0.75rem",
              fontWeight: 600,
              cursor: "pointer",
            }}
          >
            Clear Bans
          </button>
        )}
      </div>

      {/* Bottom Section: AI Recommendations & Hero Pool */}
      <div style={{ display: "grid", gridTemplateColumns: "1fr 340px", gap: "1.5rem", marginBottom: "1.5rem" }}>
        {/* Left: AI Hero Next-Pick Recommendations */}
        <div className="glass-panel" style={{ padding: "1.5rem" }}>
          <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "1.2rem" }}>
            <div style={{ display: "flex", alignItems: "center", gap: "10px" }}>
              <Sparkles size={20} color="var(--aegis-gold)" />
              <h3 className="title-dota" style={{ fontSize: "1.1rem", color: "#fff" }}>
                AI Next-Pick Recommender ({targetTeam.toUpperCase()})
              </h3>
            </div>
            <button
              onClick={fetchRecsAndItems}
              style={{
                display: "flex",
                alignItems: "center",
                gap: "6px",
                background: "rgba(255, 255, 255, 0.05)",
                border: "1px solid var(--border-subtle)",
                borderRadius: "var(--radius-sm)",
                padding: "6px 12px",
                color: "var(--text-muted)",
                fontSize: "0.8rem",
                cursor: "pointer",
              }}
            >
              <RefreshCw size={14} /> Refresh AI
            </button>
          </div>

          {loadingRecs ? (
            <div style={{ padding: "3rem", textAlign: "center", color: "var(--text-muted)" }}>
              Evaluating pairwise synergies and counter advantages across 50,000 matches...
            </div>
          ) : (
            <div style={{ display: "flex", flexDirection: "column", gap: "12px" }}>
              {recommendations.map((rec, idx) => (
                <div key={rec.hero_id} style={{
                  padding: "14px 16px",
                  background: "rgba(255, 255, 255, 0.02)",
                  border: "1px solid rgba(255, 255, 255, 0.06)",
                  borderRadius: "var(--radius-sm)",
                  display: "grid",
                  gridTemplateColumns: "160px 100px 1fr 110px",
                  gap: "1rem",
                  alignItems: "center",
                }}>
                  {/* Hero Identity */}
                  <div>
                    <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
                      <span style={{
                        width: "20px",
                        height: "20px",
                        borderRadius: "50%",
                        background: "rgba(245, 166, 35, 0.2)",
                        color: "var(--aegis-gold)",
                        display: "flex",
                        alignItems: "center",
                        justifyContent: "center",
                        fontSize: "0.75rem",
                        fontWeight: 700,
                      }}>
                        {idx + 1}
                      </span>
                      <span style={{ fontWeight: 700, color: "#fff", fontSize: "1rem" }}>{rec.hero_name}</span>
                    </div>
                    <div style={{ fontSize: "0.75rem", color: "var(--text-muted)", marginTop: "2px" }}>
                      Base WR: {(rec.base_win_rate * 100).toFixed(1)}%
                    </div>
                  </div>

                  {/* Projected Win Rate Metric */}
                  <div>
                    <div className="font-stats" style={{ fontSize: "1.25rem", color: "var(--aegis-gold)" }}>
                      {(rec.projected_win_prob * 100).toFixed(1)}%
                    </div>
                    <span className="badge badge-gold" style={{ fontSize: "0.7rem" }}>
                      {rec.win_prob_gain >= 0 ? `+${(rec.win_prob_gain * 100).toFixed(1)}% Gain` : `${(rec.win_prob_gain * 100).toFixed(1)}%`}
                    </span>
                  </div>

                  {/* Tactical Rationale */}
                  <div>
                    <div style={{ fontSize: "0.75rem", color: "var(--text-faint)", textTransform: "uppercase", marginBottom: "2px", fontWeight: 700 }}>
                      Tactical Reasoning
                    </div>
                    <div style={{ display: "flex", flexWrap: "wrap", gap: "4px" }}>
                      {rec.reasons.map((r, rIdx) => (
                        <span key={rIdx} style={{
                          fontSize: "0.78rem",
                          background: "rgba(255, 255, 255, 0.05)",
                          padding: "2px 8px",
                          borderRadius: "3px",
                          color: "#e2e8f0",
                        }}>
                          {r}
                        </span>
                      ))}
                    </div>
                  </div>

                  {/* 1-Click Draft Button */}
                  <button
                    onClick={() => addHero(rec.hero_id, targetTeam)}
                    className="btn-primary"
                    style={{ fontSize: "0.85rem", padding: "8px 12px" }}
                  >
                    Draft Hero
                  </button>
                </div>
              ))}
            </div>
          )}
        </div>

        {/* Right: Quick Hero Search & Manual Pick / Ban */}
        <div className="glass-panel" style={{ padding: "1.5rem" }}>
          <h3 className="title-dota" style={{ fontSize: "1rem", color: "#fff", marginBottom: "1rem" }}>
            Hero Roster ({filteredHeroes.length})
          </h3>

          <input
            type="text"
            placeholder="Search hero..."
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            style={{
              width: "100%",
              padding: "10px 14px",
              borderRadius: "var(--radius-sm)",
              background: "#111722",
              border: "1px solid var(--border-subtle)",
              color: "#fff",
              fontSize: "0.9rem",
              marginBottom: "12px",
              outline: "none",
            }}
          />

          <div style={{
            maxHeight: "380px",
            overflowY: "auto",
            display: "flex",
            flexDirection: "column",
            gap: "6px",
            paddingRight: "4px",
          }}>
            {filteredHeroes.slice(0, 30).map((h) => (
              <div
                key={h.hero_id}
                style={{
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "space-between",
                  padding: "8px 10px",
                  borderRadius: "4px",
                  background: "rgba(255, 255, 255, 0.02)",
                  border: "1px solid rgba(255, 255, 255, 0.04)",
                }}
              >
                <div>
                  <div style={{ fontWeight: 600, fontSize: "0.85rem", color: "#f1f5f9" }}>{h.name}</div>
                  <div style={{ fontSize: "0.72rem", color: "var(--text-muted)" }}>
                    WR: {(h.win_rate * 100).toFixed(1)}%
                  </div>
                </div>

                <div style={{ display: "flex", gap: "4px" }}>
                  <button
                    onClick={() => addHero(h.hero_id, "radiant")}
                    disabled={radiantPicks.length >= 5}
                    style={{
                      background: "rgba(0, 245, 155, 0.15)",
                      color: "var(--radiant-green)",
                      border: "1px solid rgba(0, 245, 155, 0.3)",
                      borderRadius: "4px",
                      padding: "3px 6px",
                      fontSize: "0.72rem",
                      fontWeight: 700,
                      cursor: radiantPicks.length >= 5 ? "not-allowed" : "pointer",
                      opacity: radiantPicks.length >= 5 ? 0.4 : 1,
                    }}
                  >
                    + RAD
                  </button>
                  <button
                    onClick={() => addHero(h.hero_id, "dire")}
                    disabled={direPicks.length >= 5}
                    style={{
                      background: "rgba(255, 51, 68, 0.15)",
                      color: "var(--dire-crimson)",
                      border: "1px solid rgba(255, 51, 68, 0.3)",
                      borderRadius: "4px",
                      padding: "3px 6px",
                      fontSize: "0.72rem",
                      fontWeight: 700,
                      cursor: direPicks.length >= 5 ? "not-allowed" : "pointer",
                      opacity: direPicks.length >= 5 ? 0.4 : 1,
                    }}
                  >
                    + DIRE
                  </button>
                  <button
                    onClick={() => addBan(h.hero_id)}
                    style={{
                      background: "rgba(239, 68, 68, 0.15)",
                      color: "#f87171",
                      border: "1px solid rgba(239, 68, 68, 0.3)",
                      borderRadius: "4px",
                      padding: "3px 6px",
                      fontSize: "0.72rem",
                      fontWeight: 700,
                      cursor: "pointer",
                    }}
                  >
                    + BAN
                  </button>
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* Situational Item Counter Panel (Model 5) */}
      {itemAdvice && itemAdvice.situational_counters && itemAdvice.situational_counters.length > 0 && (
        <div className="glass-panel" style={{ padding: "1.5rem", borderTop: "3px solid var(--aegis-gold)" }}>
          <div style={{ display: "flex", alignItems: "center", gap: "8px", marginBottom: "1rem" }}>
            <ShieldAlert size={20} color="var(--aegis-gold)" />
            <h3 className="title-dota" style={{ fontSize: "1.1rem", color: "#fff", margin: 0 }}>
              Situational Counter Items for {itemAdvice.hero_name} vs Opponent Lineup Threats
            </h3>
          </div>

          <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(280px, 1fr))", gap: "1rem" }}>
            {itemAdvice.situational_counters.map((item, idx) => (
              <div key={idx} style={{
                background: "rgba(255, 255, 255, 0.02)",
                border: "1px solid rgba(245, 166, 35, 0.2)",
                borderRadius: "6px",
                padding: "12px",
              }}>
                <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "4px" }}>
                  <span style={{ fontWeight: 700, color: "var(--aegis-gold)", fontSize: "0.95rem" }}>
                    {item.item_name}
                  </span>
                  <span style={{ fontSize: "0.75rem", color: "var(--mana-blue)", fontFamily: "var(--font-mono)" }}>
                    Target: ~{item.target_timing_minutes} min
                  </span>
                </div>
                <div style={{ fontSize: "0.78rem", color: "var(--text-muted)", marginBottom: "4px" }}>
                  Threat: <strong style={{ color: "#fff" }}>{item.threat_category}</strong> ({item.countering_heroes.join(", ")})
                </div>
                <div style={{ fontSize: "0.78rem", color: "#cbd5e1", fontStyle: "italic" }}>
                  "{item.strategic_rationale}"
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
